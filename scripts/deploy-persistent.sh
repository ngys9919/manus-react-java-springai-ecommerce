#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Take a fresh, persistent Ubuntu host to a running Shopwise that comes back
# after a reboot.
#
#   scripts/deploy-persistent.sh                 # deploy the checkout it lives in
#   scripts/deploy-persistent.sh --dry-run       # show what it would do
#   scripts/deploy-persistent.sh --origin https://shop.example.com
#   scripts/deploy-persistent.sh --no-systemd    # hosts without systemd
#
# The script is idempotent: running it again rebuilds and restarts the stack
# without touching .env, so the signing key and the database password - and
# therefore everyone's session - survive a redeploy.
#
# It deliberately does NOT configure TLS. See docs/DEPLOYMENT.md: terminate TLS
# with Caddy or certbot in front, because this stack only speaks plain HTTP.
# ---------------------------------------------------------------------------
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICE_NAME="shopwise"
HTTP_PORT="${SHOPWISE_HTTP_PORT:-8080}"
ORIGIN=""
DRY_RUN="false"
USE_SYSTEMD="true"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

# Run a command, or print it when --dry-run is set.
run() {
    if [ "$DRY_RUN" = "true" ]; then
        printf '    would run: %s\n' "$*"
    else
        "$@"
    fi
}

usage() {
    sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0
}

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run)     DRY_RUN="true"; shift ;;
        --no-systemd)  USE_SYSTEMD="false"; shift ;;
        --origin)      ORIGIN="${2:?--origin needs a value}"; shift 2 ;;
        --port)        HTTP_PORT="${2:?--port needs a value}"; shift 2 ;;
        --dir)         APP_DIR="${2:?--dir needs a value}"; shift 2 ;;
        -h|--help)     usage ;;
        *)             die "Unknown option: $1 (try --help)" ;;
    esac
done

[ -f "$APP_DIR/docker-compose.yml" ] || die "No docker-compose.yml in $APP_DIR - run this from a checkout of the repository."

log "Deploying Shopwise from $APP_DIR"

# ---------------------------------------------------------------------------
# 1. Docker
# ---------------------------------------------------------------------------
if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    log "Docker and the Compose plugin are already installed"
else
    log "Installing Docker (docker.io + docker-compose-v2)"
    run sudo apt-get update -qq
    run sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker.io docker-compose-v2
fi

COMPOSE="docker compose"

# ---------------------------------------------------------------------------
# 2. The Docker daemon, enabled so the stack can survive a reboot
# ---------------------------------------------------------------------------
if [ "$DRY_RUN" = "false" ]; then
    sudo systemctl enable --now docker >/dev/null 2>&1 || sudo service docker start >/dev/null 2>&1 || true
    docker info >/dev/null 2>&1 || die "The Docker daemon is not reachable."
else
    echo "    would enable and start docker.service"
fi

# ---------------------------------------------------------------------------
# 3. Secrets
#
# .env is the only place the signing key and the database password live, and it
# is generated exactly once. Rewriting it would invalidate every session and
# lock the API out of its own database, because PostgreSQL only applies
# POSTGRES_PASSWORD when it initialises an empty data directory.
# ---------------------------------------------------------------------------
ENV_FILE="$APP_DIR/.env"
if [ -f "$ENV_FILE" ]; then
    log ".env already exists - leaving it untouched"
    if ! grep -q '^SHOPWISE_JWT_SECRET=.\+' "$ENV_FILE"; then
        die "SHOPWISE_JWT_SECRET in .env is empty. Generate one with 'openssl rand -base64 48' and add it, or delete .env to have this script create a new one (that also resets the database password)."
    fi
else
    command -v openssl >/dev/null 2>&1 || die "openssl is required to generate secrets (apt-get install openssl)."
    log "Creating .env with freshly generated secrets"
    if [ "$DRY_RUN" = "true" ]; then
        echo "    would write $ENV_FILE with a generated SHOPWISE_JWT_SECRET and SHOPWISE_DB_PASSWORD"
    else
        umask 077
        cat > "$ENV_FILE" <<EOF
# Generated by scripts/deploy-persistent.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Contains the signing key and the database password. Never commit it, and keep
# it if you keep the database volume - losing it means losing access to the data.
SHOPWISE_JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
SHOPWISE_DB_NAME=shopwise
SHOPWISE_DB_USER=shopwise
# Hex, not base64: the password is interpolated into a JDBC URL and a shell
# environment by Compose, and a stray / or + is one quoting mistake away from a
# database the API cannot reach. 16 bytes is 128 bits.
SHOPWISE_DB_PASSWORD=$(openssl rand -hex 16)
SHOPWISE_HTTP_PORT=$HTTP_PORT
EOF
    fi
fi

# ---------------------------------------------------------------------------
# 4. Browser origins
#
# Not strictly required: the backend trusts a browser's own "this is
# same-origin" signal, so a deployment at any hostname works without this. It
# is set anyway, so that a client which cannot send that signal - an old
# browser, or a proxy that strips it - still works instead of getting a 403.
# ---------------------------------------------------------------------------
if [ -n "$ORIGIN" ] && [ "$DRY_RUN" = "false" ]; then
    case "$ORIGIN" in
        *://*) ;;
        *) ORIGIN="https://$ORIGIN" ;;
    esac
    host="${ORIGIN#*://}"
    log "Allowing browser origin $host"
    patterns="$ORIGIN,https://$host,http://$host"
    if grep -q '^SHOPWISE_ALLOWED_ORIGIN_PATTERNS=' "$ENV_FILE"; then
        sed -i "s|^SHOPWISE_ALLOWED_ORIGIN_PATTERNS=.*|SHOPWISE_ALLOWED_ORIGIN_PATTERNS=$patterns|" "$ENV_FILE"
    else
        printf 'SHOPWISE_ALLOWED_ORIGIN_PATTERNS=%s\n' "$patterns" >> "$ENV_FILE"
    fi
elif [ -n "$ORIGIN" ]; then
    echo "    would allow browser origin $ORIGIN"
fi

# ---------------------------------------------------------------------------
# 5. Build and start
# ---------------------------------------------------------------------------
log "Building and starting the stack (the first build downloads Maven and npm dependencies)"
run sudo docker compose -f "$APP_DIR/docker-compose.yml" up -d --build

# ---------------------------------------------------------------------------
# 6. Auto-start on boot
# ---------------------------------------------------------------------------
if [ "$USE_SYSTEMD" = "true" ]; then
    log "Installing the systemd unit so the site returns after a reboot"
    if [ "$DRY_RUN" = "true" ]; then
        echo "    would render $APP_DIR/deploy/shopwise.service into /etc/systemd/system/$SERVICE_NAME.service (WorkingDirectory=$APP_DIR)"
    else
        sed "s|__APP_DIR__|$APP_DIR|g" "$APP_DIR/deploy/shopwise.service" \
            | sudo tee "/etc/systemd/system/$SERVICE_NAME.service" >/dev/null
        sudo systemctl daemon-reload
        sudo systemctl enable "$SERVICE_NAME" >/dev/null
    fi
fi

# ---------------------------------------------------------------------------
# 7. Firewall
#
# A Cloud Computer starts with only SSH and ICMP open, so an unopened port is
# indistinguishable from a crashed service when you try the URL.
# ---------------------------------------------------------------------------
if command -v ufw >/dev/null 2>&1 && sudo ufw status 2>/dev/null | grep -q "^Status: active"; then
    log "Allowing port $HTTP_PORT through ufw"
    run sudo ufw allow "$HTTP_PORT"/tcp
else
    log "ufw is not active - no firewall rule needed"
fi

# ---------------------------------------------------------------------------
# 8. Wait for health
# ---------------------------------------------------------------------------
if [ "$DRY_RUN" = "true" ]; then
    echo "    would wait for the containers to report healthy"
    log "Dry run complete - nothing was changed."
    exit 0
fi

log "Waiting for the containers to become healthy"
deadline=$(( SECONDS + 300 ))
while [ $SECONDS -lt $deadline ]; do
    unhealthy="$(docker compose -f "$APP_DIR/docker-compose.yml" ps --format '{{.Name}} {{.Health}}' 2>/dev/null \
        | grep -v -e 'healthy' -e '^\s*$' || true)"
    if [ -z "$unhealthy" ] && docker compose -f "$APP_DIR/docker-compose.yml" ps --format '{{.Health}}' 2>/dev/null | grep -q healthy; then
        break
    fi
    sleep 5
done

echo
docker compose -f "$APP_DIR/docker-compose.yml" ps
echo

ip="$(ip route get 1.1.1.1 2>/dev/null | awk '{print $7; exit}')"
echo "----------------------------------------------------------------"
echo "Shopwise is running."
echo "  URL         http://${ip:-<host>}:$HTTP_PORT"
echo "  API docs    http://${ip:-<host>}:$HTTP_PORT/swagger-ui.html"
echo "  Logs        docker compose -f $APP_DIR/docker-compose.yml logs -f"
echo
echo "Next, for a permanent public site:"
echo "  1. Point a domain's A record at this host, then terminate TLS in front -"
echo "     see docs/DEPLOYMENT.md. This stack serves plain HTTP only."
echo "  2. If the host bills for outbound traffic, enable auto top-up. Traffic"
echo "     exhaustion shuts the machine down."
echo "----------------------------------------------------------------"
